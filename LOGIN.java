    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        String user = jTextField1.getText().trim();
        String pass = new String(jPasswordField1.getPassword()).trim();

        // Validasi jika kolom kosong
        if (user.isEmpty() || pass.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Username dan Password tidak boleh kosong!", "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }

        // Koneksi ke Database MySQL XAMPP (Pastikan database db_iuran_rt sudah dibuat di phpMyAdmin)
        String url = "jdbc:mysql://localhost:3306/db_iuran_rt";
        String dbUser = "root";
        String dbPass = "";

        // Query untuk mengecek data admin di database
        String sql = "SELECT * FROM tb_admin WHERE username = ? AND password = ?";

        try (Connection conn = DriverManager.getConnection(url, dbUser, dbPass);
             PreparedStatement pst = conn.prepareStatement(sql)) {

            pst.setString(1, user);
            pst.setString(2, pass);
            ResultSet rs = pst.executeQuery();

            if (rs.next()) {
                JOptionPane.showMessageDialog(this, "Login Berhasil! Selamat datang, " + rs.getString("nama_lengkap"));
                // Di sini nanti bisa lanjut membuka JFrame Menu Utama / Dashboard
            } else {
                JOptionPane.showMessageDialog(this, "Username atau Password salah!", "Gagal Login", JOptionPane.ERROR_MESSAGE);
            }

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Koneksi Database Gagal: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

